#!/usr/bin/env python3
"""Generate the statistics registry's code from crates/econ-core/indicators.toml.

Writes:
  1. crates/econ-core/src/indicators_gen.rs: `enum IndicatorId` and the static
     metadata `INDICATORS` (spec game/statistics-registry).
  2. ui/src/generated/indicators.json: the same for the UI.

Usage:
    python scripts/codegen_indicators.py           # write
    python scripts/codegen_indicators.py --check   # verify (CI / just check)

The registry is checked here: unique dotted ids, known units, periods,
breakdowns, aggregates and views, derivations naming other entries, `sum` only
over counts and money, headline entries in the overview.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "crates" / "econ-core" / "indicators.toml"
OUT_RS = ROOT / "crates" / "econ-core" / "src" / "indicators_gen.rs"
OUT_UI = ROOT / "ui" / "src" / "generated" / "indicators.json"

UNITS = {"bani": "Bani", "real_bani": "RealBani", "ppm": "Ppm", "persons": "Persons",
         "index_ppm": "IndexPpm", "milli": "Milli", "count": "Count"}
PERIODS = {"month": "Month", "day": "Day"}
BREAKDOWNS = {"region": "Region", "county": "County", "industry": "Industry", "class": "Class",
              "fifth": "Fifth", "age_band": "AgeBand", "sex": "Sex", "edu": "Edu", "activity": "Activity",
              "level": "Level", "flow": "Flow", "line": "Line", "good": "Good"}
AGGREGATES = {"sum": "Sum", "mean": "Mean", "none": "None"}
VIEWS = {"overview": "Overview", "budget": "Budget", "prices": "Prices", "finance": "Finance",
         "trade": "Trade", "people": "People", "informal": "Informal", "map": "Map"}
STATUSES = {"active": "Active", "planned": "Planned"}
DERIVES = {"ratio": ("Ratio", 2), "real": ("Real", 1), "growth_yoy": ("GrowthYoy", 1),
           "growth_mom": ("GrowthMom", 1), "per_capita": ("PerCapita", 1)}
NAME = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$")


class RegistryError(Exception):
    pass


def variant(name: str) -> str:
    """`gdp.per_capita` -> `GdpPerCapita`."""
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[._]", name) if p)


def parse_derive(text: str, names: set[str], own: str) -> tuple[str, list[str]] | None:
    if not text:
        return None
    m = re.fullmatch(r"([a-z_]+)\(([^)]*)\)", text.replace(" ", ""))
    if not m or m.group(1) not in DERIVES:
        raise RegistryError(f"{own}: derive {text!r} is not one of {sorted(DERIVES)}")
    op, arity = DERIVES[m.group(1)]
    args = [a for a in m.group(2).split(",") if a]
    if len(args) != arity:
        raise RegistryError(f"{own}: {m.group(1)} takes {arity} input(s)")
    for a in args:
        if a not in names or a == own:
            raise RegistryError(f"{own}: derive input {a!r} is not another entry")
    return op, args


def load(path: Path = REGISTRY) -> list[dict]:
    entries = tomllib.loads(path.read_text(encoding="utf-8"))["indicator"]
    names = [e["id"] for e in entries]
    if len(set(names)) != len(names):
        raise RegistryError("an id is listed twice")
    for e in entries:
        n = e["id"]
        if not NAME.match(n):
            raise RegistryError(f"{n}: not a dotted lowercase name")
        for field, known in (("unit", UNITS), ("period", PERIODS), ("aggregate", AGGREGATES),
                             ("status", STATUSES)):
            if e[field] not in known:
                raise RegistryError(f"{n}: unknown {field} {e[field]!r}")
        for b in e["breakdowns"]:
            if b not in BREAKDOWNS:
                raise RegistryError(f"{n}: unknown breakdown {b!r}")
        for v in e["views"]:
            if v not in VIEWS:
                raise RegistryError(f"{n}: unknown view {v!r}")
        if len(set(e["breakdowns"])) != len(e["breakdowns"]) or len(set(e["views"])) != len(e["views"]):
            raise RegistryError(f"{n}: a breakdown or view listed twice")
        if e["aggregate"] == "sum" and e["unit"] not in ("bani", "real_bani", "persons", "count"):
            raise RegistryError(f"{n}: aggregate sum over {e['unit']}")
        if e["headline"] and "overview" not in e["views"]:
            raise RegistryError(f"{n}: a headline entry outside the overview")
        e["_derive"] = parse_derive(e["derive"], set(names), n)
    return entries


def rust(entries: list[dict]) -> str:
    def opt(s: str) -> str:
        return f'Some("{s}")' if s else "None"

    def derive(d) -> str:
        if d is None:
            return "None"
        op, args = d
        return f"Some(Derive::{op}(" + ", ".join(f"IndicatorId::{variant(a)}" for a in args) + "))"

    lines = [
        "//! GENERATED by scripts/codegen_indicators.py from crates/econ-core/indicators.toml — do not edit.",
        "",
        "use crate::stats::{Aggregate, Breakdown, Derive, IndicatorMeta, Period, Status, Unit, View};",
        "",
        "/// Every indicator of the registry (spec game/statistics-registry).",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]",
        "#[allow(missing_docs)]",
        "pub enum IndicatorId {",
    ]
    lines += [f"    {variant(e['id'])}," for e in entries]
    lines += ["}", "", "/// The registry's entries, in its order.",
              f"pub(crate) static INDICATORS: [IndicatorMeta; {len(entries)}] = ["]
    for e in entries:
        lines += [
            "    IndicatorMeta {",
            f"        id: IndicatorId::{variant(e['id'])},",
            f'        name: "{e["id"]}",',
            f'        glossary: "{e["glossary"]}",',
            f"        unit: Unit::{UNITS[e['unit']]},",
            f"        period: Period::{PERIODS[e['period']]},",
            "        breakdowns: &[" + ", ".join(f"Breakdown::{BREAKDOWNS[b]}" for b in e["breakdowns"]) + "],",
            f"        aggregate: Aggregate::{AGGREGATES[e['aggregate']]},",
            f"        derive: {derive(e['_derive'])},",
            f"        feature: {opt(e['feature'])},",
            "        views: &[" + ", ".join(f"View::{VIEWS[v]}" for v in e["views"]) + "],",
            f"        headline: {'true' if e['headline'] else 'false'},",
            f"        status: Status::{STATUSES[e['status']]},",
            "    },",
        ]
    lines += ["];", ""]
    return "\n".join(lines)


def rustfmt(text: str) -> str:
    """The text as `cargo fmt` leaves it (the repository's rustfmt settings)."""
    exe = shutil.which("rustfmt")
    if exe is None:
        raise RegistryError("rustfmt is not on PATH (the generated code is formatted with it)")
    out = subprocess.run([exe, "--edition", "2024", "--emit", "stdout"], input=text, capture_output=True,
                         text=True, check=True, cwd=ROOT)
    return out.stdout


def ui(entries: list[dict]) -> str:
    keep = ("id", "glossary", "unit", "period", "breakdowns", "aggregate", "derive", "feature", "views",
            "headline", "milestone", "status", "source")
    return json.dumps([{k: e[k] for k in keep} for e in entries], indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    try:
        entries = load()
    except RegistryError as e:
        print(f"indicators.toml: {e}")
        return 1
    try:
        rs = rustfmt(rust(entries))
    except (RegistryError, subprocess.CalledProcessError) as e:
        print(f"indicators: {e}")
        return 1
    outputs = {OUT_RS: rs, OUT_UI: ui(entries)}
    stale = []
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("stale generated files (run `just codegen`): " + ", ".join(map(str, stale)))
        return 1
    print(f"OK — {'checked' if check else 'wrote'} the indicator codegen ({len(entries)} indicators).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
