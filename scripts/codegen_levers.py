#!/usr/bin/env python3
"""Generate code from the lever registry (spec game/lever-system, ADR-0018).

Reads crates/econ-core/levers.toml and writes:
  1. crates/econ-core/src/levers_gen.rs: `enum LeverId`, `LeverId::ALL` and
     the dotted ids;
  2. ui/src/generated/levers.json: the list the app builds its panels from;
  3. crates/econ-core/tests/generated_lever_list.rs: the list the coverage
     tests iterate.
`--check` fails if a generated file is out of date (CI). `--registry PATH`
reads another registry file (AC-LEV-01 checks a stale one).

Usage:
    python scripts/codegen_levers.py                    # regenerate
    python scripts/codegen_levers.py --check            # verify (CI / just check)
    python scripts/codegen_levers.py --check --registry PATH
"""
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "crates" / "econ-core" / "levers.toml"
OUT_RS = ROOT / "crates" / "econ-core" / "src" / "levers_gen.rs"
OUT_UI = ROOT / "ui" / "src" / "generated" / "levers.json"
OUT_TEST = ROOT / "crates" / "econ-core" / "tests" / "generated_lever_list.rs"


def variant(lever_id: str) -> str:
    """`tax.vat.rate_reduced_2` -> `TaxVatRateReduced2`."""
    parts = lever_id.replace(".", "_").split("_")
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_rs(levers: list[dict]) -> str:
    n = len(levers)
    out = [
        "//! GENERATED by scripts/codegen_levers.py from crates/econ-core/levers.toml — do not edit.",
        "//! The lever ids, one per registry entry, in registry order (ADR-0018).",
        "",
        "/// The lever ids, one per registry entry, in registry order.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]",
        "pub enum LeverId {",
    ]
    for lv in levers:
        out.append(f"    /// `{lv['id']}`")
        out.append(f"    {variant(lv['id'])},")
    out += [
        "}",
        "",
        "/// The dotted ids, in the order of [`LeverId::ALL`].",
        f"const IDS: [&str; {n}] = [",
    ]
    out += [f"    {rust_str(lv['id'])}," for lv in levers]
    out += [
        "];",
        "",
        "impl LeverId {",
        "    /// Every lever, in registry order.",
        f"    pub const ALL: [LeverId; {n}] = [",
    ]
    out += [f"        LeverId::{variant(lv['id'])}," for lv in levers]
    out += [
        "    ];",
        "",
        "    /// The stable dotted id, e.g. `tax.vat.rate_standard`.",
        "    #[must_use]",
        "    pub fn as_str(self) -> &'static str {",
        "        IDS[self as usize]",
        "    }",
        "",
        "    /// The lever of a dotted id, if the registry has it.",
        "    #[must_use]",
        "    pub fn from_id(id: &str) -> Option<LeverId> {",
        "        IDS.iter().position(|&s| s == id).map(|i| LeverId::ALL[i])",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


def render_ui(levers: list[dict], tables: dict) -> str:
    rows = []
    for lv in levers:
        row = {
            "id": lv["id"],
            "label": lv["label"],
            "group": lv["group"],
            "shape": lv["shape"],
            "unit": lv["unit"],
            "range": lv.get("range"),
            "milestone": lv["milestone"],
            "status": lv["status"],
        }
        if "rows" in lv:
            row["rows"] = lv["rows"]
        if "key" in lv:
            row["key"] = lv["key"]
            # Scenario tables (industries, budget lines, public units) are
            # filled by the app from the scenario.
            row["keys"] = lv.get("keys", tables.get(lv["key"]))
        if "options" in lv:
            row["options"] = lv["options"]
        rows.append(row)
    return json.dumps({"levers": rows}, indent=2, ensure_ascii=False) + "\n"


def render_test(levers: list[dict]) -> str:
    out = [
        "//! GENERATED by scripts/codegen_levers.py from crates/econ-core/levers.toml — do not edit.",
        "//! The list the coverage tests iterate (spec game/lever-system, AC-LEV-02, AC-LEV-14).",
        "#![cfg(feature = \"levers\")]",
        "",
        "/// Every lever's dotted id and milestone, in registry order.",
        "pub const LEVERS: &[(&str, &str)] = &[",
    ]
    out += [f"    ({rust_str(lv['id'])}, {rust_str(lv['milestone'])})," for lv in levers]
    out += [
        "];",
        "",
        "/// The generated list is the registry's.",
        "#[test]",
        "fn generated_list_matches_the_registry() {",
        "    let ids: Vec<&str> = econ_core::levers::LeverId::ALL",
        "        .iter()",
        "        .map(|l| l.as_str())",
        "        .collect();",
        "    let listed: Vec<&str> = LEVERS.iter().map(|&(id, _)| id).collect();",
        "    assert_eq!(ids, listed);",
        "}",
        "",
    ]
    return "\n".join(out)


READERS = {
    "Commands", "Plan", "Staffing", "Prices", "OutputAndInputs", "FixedDemand",
    "Households", "GoodsMarket", "Quits", "Pay", "WageRound", "MonthlyClose", "Checks",
}
SCENARIO_TABLES = {"industries", "budget_lines", "public_units", "counties", "blocs", "fuels"}


def registry_faults(levers: list[dict], tables: dict) -> list[str]:
    """The spec's registry checks against the repository (spec, "Checks"):
    `spec` in the docs index, `glossary` a glossary name, a known reader and
    key table. The Rust `Registry::check` makes the same checks (AC-LEV-01)."""
    index = (ROOT / "docs" / "INDEX.md").read_text(encoding="utf-8")
    specs = {
        cells[2].strip().strip("`")
        for line in index.splitlines()
        if line.startswith("| [") and len(cells := line.split("|")) > 2
    }
    glossary = (ROOT / "crates" / "econ-types" / "src" / "glossary.rs").read_text(encoding="utf-8")
    names = set(re.findall(r'code_name: "([^"]+)"', glossary))
    faults = []
    for lv in levers:
        i = lv.get("id", "?")
        if lv.get("spec") not in specs:
            faults.append(f"{i}: spec `{lv.get('spec')}` is not in the docs index")
        if lv.get("glossary") not in names:
            faults.append(f"{i}: glossary `{lv.get('glossary')}` is not a glossary name")
        if lv.get("reader") not in READERS:
            faults.append(f"{i}: unknown reader `{lv.get('reader')}`")
        key = lv.get("key")
        if key is not None and key not in tables and key not in SCENARIO_TABLES:
            faults.append(f"{i}: no key table `{key}`")
    return faults


def main() -> int:
    args = sys.argv[1:]
    registry = REGISTRY
    if "--registry" in args:
        registry = Path(args[args.index("--registry") + 1])
    data = tomllib.loads(registry.read_text(encoding="utf-8"))
    levers = data.get("lever", [])
    tables = data.get("key_tables", {})
    ids = [lv.get("id", "") for lv in levers]
    dups = sorted({i for i in ids if ids.count(i) > 1})
    if dups:
        print("Duplicate lever ids in the registry:", dups)
        return 1
    faults = registry_faults(levers, tables)
    if faults:
        print("The lever registry fails its checks:\n  " + "\n  ".join(faults))
        return 1
    outputs = [
        (OUT_RS, render_rs(levers)),
        (OUT_UI, render_ui(levers, tables)),
        (OUT_TEST, render_test(levers)),
    ]
    if "--check" in args:
        stale = [
            p.relative_to(ROOT).as_posix()
            for p, content in outputs
            if not p.exists() or p.read_text(encoding="utf-8") != content
        ]
        if stale:
            print(f"Stale lever codegen: {', '.join(stale)}. Run: python scripts/codegen_levers.py")
            return 1
        print(f"OK — lever codegen up to date ({len(levers)} levers).")
        return 0
    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"OK — wrote the lever codegen ({len(levers)} levers).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
